// Regenerate `src/nodes/index.ts` — the barrel that imports every built-in
// flow-node kind module for its `registerNodeKind(...)` side effect.
//
// Adding a flow-node kind is meant to be "drop one file under src/nodes/" with
// NO hand-edit to any shared surface — including this barrel. So the barrel is
// GENERATED, not hand-maintained: this script scans `src/nodes/*.ts` (excluding
// the barrel itself and the non-kind support module `registry.ts`), sorts them,
// and writes their side-effect imports in a deterministic order. It runs as a
// prebuild step, so a sibling slice that adds `src/nodes/<kind>.ts` gets it wired
// automatically and two slices adding different files merge without conflict.

import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const nodesDir = join(here, "..", "src", "nodes");

// Support modules that are imported by name, not for a registration side effect.
const NOT_KIND_MODULES = new Set(["index.ts", "registry.ts"]);

const modules = readdirSync(nodesDir)
  .filter((f) => f.endsWith(".ts") && !NOT_KIND_MODULES.has(f))
  .map((f) => f.slice(0, -3))
  .sort((a, b) => a.localeCompare(b, "en"));

const banner =
  "// GENERATED by scripts/gen-node-registry.mjs — do not edit by hand.\n" +
  "//\n" +
  "// The barrel of built-in flow-node kind modules. Importing this module runs\n" +
  "// every kind's `registerNodeKind(...)` side effect, populating the dispatch\n" +
  "// table `makeBuilder`/`walkNodes`/the emitter route through. A new kind is\n" +
  "// picked up automatically by re-running the generator (a prebuild step) — no\n" +
  "// hand-edit here.\n";

const body = modules.map((m) => `import "./${m}.js";`).join("\n");
const out = `${banner}\n${body}\n`;

writeFileSync(join(nodesDir, "index.ts"), out);
process.stdout.write(`gen-node-registry: wired ${modules.length} kind modules (${modules.join(", ")})\n`);
